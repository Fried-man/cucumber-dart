// Generates lib/src/glue/function_shapes.g.dart.
//
// Run from the package root: dart run tool/generate_function_shapes.dart
//
// Dart has no mirrors on Flutter or AOT, but function types are reified, so
// `f is Function(Never, Never)` tells us that f can be called with two
// positional arguments, and `f is Function(T, Never)` that its first parameter
// accepts a T (design §4.5).
import 'dart:io';

const int maxArity = 12;

void main() {
  final out = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND.')
    ..writeln('// Generated by tool/generate_function_shapes.dart.')
    ..writeln()
    ..writeln(
      '/// The highest arity supported for glue bodies and transformers.',
    )
    ..writeln('const int maxArity = $maxArity;')
    ..writeln()
    ..writeln('/// Whether [f] can be called with exactly [arity] positional')
    ..writeln('/// arguments (and no named ones).')
    ..writeln('bool hasArity(Function f, int arity) {')
    ..writeln('  switch (arity) {');
  for (var a = 0; a <= maxArity; a++) {
    out
      ..writeln('    case $a:')
      ..writeln('      return f is Object? Function(${_params(a, -1)});');
  }
  out
    ..writeln('    default:')
    ..writeln('      return false;')
    ..writeln('  }')
    ..writeln('}')
    ..writeln()
    ..writeln('/// Whether parameter [index] of [f], called with [arity]')
    ..writeln('/// positional arguments, accepts a value of type [T].')
    ..writeln('bool acceptsAt<T>(Function f, int index, int arity) {')
    ..writeln('  switch ((arity, index)) {');
  for (var a = 1; a <= maxArity; a++) {
    for (var i = 0; i < a; i++) {
      out
        ..writeln('    case ($a, $i):')
        ..writeln('      return f is Object? Function(${_params(a, i)});');
    }
  }
  out
    ..writeln('    default:')
    ..writeln('      return false;')
    ..writeln('  }')
    ..writeln('}');

  const path = 'lib/src/glue/function_shapes.g.dart';
  File(path)
    ..createSync(recursive: true)
    ..writeAsStringSync(out.toString());
  final format = Process.runSync(Platform.resolvedExecutable, ['format', path]);
  stdout.write(format.stdout);
  stderr.write(format.stderr);
}

String _params(int arity, int typed) =>
    [for (var i = 0; i < arity; i++) i == typed ? 'T' : 'Never'].join(', ');
