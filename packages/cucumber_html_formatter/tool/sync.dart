// Synchronises the prebuilt assets of @cucumber/html-formatter into
// `lib/src/assets.g.dart` from the pinned npm tarball, after verifying its
// published SHA-512 integrity.
//
//   dart run tool/sync.dart          # (re)write lib/src/assets.g.dart
//   dart run tool/sync.dart --check  # exit 1 when it differs (CI drift check)
//
// The assets are the files the upstream wrappers (JavaScript, Java, Ruby,
// .NET) read at run time: the `index.mustache` template, the report script
// `main.js` and its third-party notices `main.js.LICENSE.txt`, the style
// sheet `main.css`, and the favicon `icon.url`. Each is embedded in a Dart
// string literal, together with the SHA-256 of its bytes, so the tests can
// check that the embedding is lossless. `.gitattributes` keeps git from
// rewriting the generated file. See docs/design.md (§8.2, §9).
import 'dart:collection';
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:crypto/crypto.dart';

/// The pinned `@cucumber/html-formatter` release. Update together with
/// [_integrity] and the package version in pubspec.yaml.
const String _upstreamVersion = '24.2.0';

/// The npm `dist.integrity` of [_upstreamVersion].
const String _integrity =
    'sha512-6Y5ijKyFeNiaMdcYna/fo1Bluzebm8L+vSAyuymIt7Dxu5Fq1sDYMGqR1rYeuNdJmXyu/YRtGLOsrZdCJCQGIg==';

final Uri _tarballUrl = Uri.parse(
  'https://registry.npmjs.org/@cucumber/html-formatter/-/'
  'html-formatter-$_upstreamVersion.tgz',
);

const String _generatedFile = 'lib/src/assets.g.dart';

/// An asset of the tarball and the Dart constant it is embedded in.
typedef _Asset = ({String entry, String name, String constant, String doc});

const List<_Asset> _assets = [
  (
    entry: 'package/dist/src/index.mustache',
    name: 'index.mustache',
    constant: 'indexMustache',
    doc:
        'The HTML template of the report, with the placeholders `{{title}}`,\n'
        '`{{icon}}`, `{{css}}`, `{{custom_css}}`, `{{messages}}`, `{{script}}`\n'
        'and `{{custom_script}}`.',
  ),
  (
    entry: 'package/dist/main.js',
    name: 'main.js',
    constant: 'mainJs',
    doc:
        'The report script: renders `window.CUCUMBER_MESSAGES` with the Cucumber\n'
        'React components. It bundles third-party code; see [mainJsLicense].',
  ),
  (
    entry: 'package/dist/main.js.LICENSE.txt',
    name: 'main.js.LICENSE.txt',
    constant: 'mainJsLicense',
    doc: 'The licence notices of the third-party code bundled in [mainJs].',
  ),
  (
    entry: 'package/dist/main.css',
    name: 'main.css',
    constant: 'mainCss',
    doc: 'The style sheet of the report.',
  ),
  (
    entry: 'package/dist/src/icon.url',
    name: 'icon.url',
    constant: 'iconUrl',
    doc: 'The favicon of the report (the Cucumber logo), as a `data:` URL.',
  ),
];

/// The placeholders of `index.mustache`, in the order the writer fills them.
const List<String> _placeholders = [
  '{{title}}',
  '{{icon}}',
  '{{css}}',
  '{{custom_css}}',
  '{{messages}}',
  '{{script}}',
  '{{custom_script}}',
];

/// Entry point; see the file header for usage.
Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  if (args.any((arg) => arg != '--check')) {
    stderr.writeln('Usage: dart run tool/sync.dart [--check]');
    exitCode = 64;
    return;
  }

  final packageDir = Directory.fromUri(Platform.script.resolve('../'));
  final tarball = await _download(_tarballUrl);
  _verifyIntegrity(tarball);
  final entries = _extractFiles(gzip.decode(tarball));
  final expected = utf8.encode(_generate(entries));
  final generated = File.fromUri(packageDir.uri.resolve(_generatedFile));
  const label = '@cucumber/html-formatter@$_upstreamVersion';

  if (check) {
    if (!generated.existsSync()) {
      _outOfSync('missing:    $_generatedFile', label);
    } else if (!_sameBytes(generated.readAsBytesSync(), expected)) {
      _outOfSync('changed:    $_generatedFile', label);
    } else {
      stdout.writeln(
        '$_generatedFile matches $label (${_assets.length} assets).',
      );
    }
    return;
  }

  generated.parent.createSync(recursive: true);
  generated.writeAsBytesSync(expected, flush: true);
  stdout.writeln(
    'Wrote ${_assets.length} assets from $label to ${generated.path}',
  );
}

void _outOfSync(String problem, String label) {
  stderr
    ..writeln('Generated assets are out of sync with $label:')
    ..writeln('  $problem')
    ..writeln('Run: dart run tool/sync.dart');
  exitCode = 1;
}

/// The content of [_generatedFile] for the tarball [entries].
String _generate(Map<String, List<int>> entries) {
  final out = StringBuffer()
    ..write('''
// Generated by tool/sync.dart from the prebuilt assets of
// @cucumber/html-formatter@$_upstreamVersion (npm).
// Do not edit; run `dart run tool/sync.dart` instead.

/// The version of `@cucumber/html-formatter` whose assets are embedded.
const String htmlFormatterVersion = '$_upstreamVersion';
''');
  final digests = SplayTreeMap<String, String>();
  for (final asset in _assets) {
    final bytes = entries[asset.entry];
    if (bytes == null) {
      throw StateError('${asset.entry} is missing from $_tarballUrl');
    }
    // Fails on invalid UTF-8: the assets are embedded as Dart strings.
    final content = utf8.decode(bytes);
    if (asset.name == 'index.mustache') {
      _verifyTemplate(content);
    }
    digests[asset.name] = '${sha256.convert(bytes)}';
    out
      ..writeln()
      ..writeAll(asset.doc.split('\n').map((line) => '/// $line\n'))
      ..writeln('///')
      ..writeln('/// Upstream file: `${asset.entry.substring(8)}`.')
      ..writeln('const String ${asset.constant} = ${_literal(content)};');
  }
  out
    ..writeln()
    ..writeln(
      '/// The SHA-256 of the UTF-8 bytes of each embedded asset, by file name.',
    )
    ..writeln('const Map<String, String> assetSha256 = {');
  for (final MapEntry(key: name, value: digest) in digests.entries) {
    // Laid out as `dart format` does, so the drift check survives it.
    final line = "  '$name': '$digest',";
    out.writeln(line.length <= 80 ? line : "  '$name':\n      '$digest',");
  }
  out.writeln('};');
  return out.toString();
}

/// [content] as a multi-line Dart string literal.
///
/// The line break after the opening quotes is dropped by Dart, so [content]
/// is kept exactly, including its first and last characters. `\` and `$` are
/// escaped, and so are carriage returns (which Dart would normalise) and the
/// bidirectional formatting characters that the analyzer reports in literals
/// (`text_direction_code_point_in_literal`); `main.js` has some. A `'` is
/// escaped only where it would end the literal (every third of a run, and
/// the last character), as `unnecessary_string_escapes` wants.
String _literal(String content) {
  final escaped = content.replaceAllMapped(
    RegExp("[\\\\\$\r\u202A-\u202E\u2066-\u2069]|'+"),
    (match) {
      final text = match[0]!;
      if (text.startsWith("'")) {
        final atEnd = match.end == content.length;
        return [
          for (var i = 0; i < text.length; i++)
            i % 3 == 2 || (atEnd && i == text.length - 1) ? r"\'" : "'",
        ].join();
      }
      return switch (text) {
        '\r' => r'\r',
        _ when text.codeUnitAt(0) > 0x7F =>
          '\\u${text.codeUnitAt(0).toRadixString(16).toUpperCase()}',
        _ => '\\$text',
      };
    },
  );
  return "'''\n$escaped'''";
}

void _verifyTemplate(String template) {
  var from = 0;
  for (final placeholder in _placeholders) {
    final index = template.indexOf(placeholder, from);
    if (index < 0 || template.indexOf(placeholder, index + 1) >= 0) {
      throw StateError(
        'index.mustache must contain $placeholder once, after the previous '
        'placeholders ($_placeholders)',
      );
    }
    from = index + placeholder.length;
  }
}

Future<Uint8List> _download(Uri url) async {
  final client = HttpClient();
  try {
    final response = await (await client.getUrl(url)).close();
    if (response.statusCode != HttpStatus.ok) {
      throw HttpException(
        'GET $url failed with HTTP ${response.statusCode}',
        uri: url,
      );
    }
    final builder = BytesBuilder(copy: false);
    await response.forEach(builder.add);
    return builder.takeBytes();
  } finally {
    client.close();
  }
}

void _verifyIntegrity(List<int> bytes) {
  final actual = 'sha512-${base64.encode(sha512.convert(bytes).bytes)}';
  if (actual != _integrity) {
    throw StateError(
      'Integrity mismatch for $_tarballUrl\n'
      '  expected: $_integrity\n'
      '  actual:   $actual',
    );
  }
}

/// Returns the regular files of an uncompressed tar archive, keyed by their
/// `/`-separated path.
Map<String, List<int>> _extractFiles(List<int> tar) {
  final files = <String, List<int>>{};
  String? paxPath;
  var offset = 0;
  while (offset + 512 <= tar.length) {
    final header = tar.sublist(offset, offset + 512);
    if (header.every((byte) => byte == 0)) {
      break; // End-of-archive marker.
    }
    final sizeField = _field(header, 124, 12).trim();
    final size = sizeField.isEmpty ? 0 : int.parse(sizeField, radix: 8);
    final dataStart = offset + 512;
    final data = tar.sublist(dataStart, dataStart + size);
    offset = dataStart + ((size + 511) ~/ 512) * 512;

    final type = header[156];
    if (type == 0x78) {
      // 'x': PAX extended header describing the next entry.
      paxPath = _paxPath(data);
    } else if (type == 0x30 || type == 0x00) {
      // '0' or NUL: regular file.
      files[paxPath ?? _ustarName(header)] = data;
      paxPath = null;
    } else if (type != 0x67) {
      // Anything else except a global PAX header ('g'): directories, links.
      paxPath = null;
    }
  }
  return files;
}

String _ustarName(List<int> header) {
  final name = _field(header, 0, 100);
  final isUstar = _field(header, 257, 6).startsWith('ustar');
  final prefix = isUstar ? _field(header, 345, 155) : '';
  return prefix.isEmpty ? name : '$prefix/$name';
}

String _field(List<int> header, int start, int length) {
  final bytes = header.sublist(start, start + length);
  final end = bytes.indexOf(0);
  return utf8.decode(end < 0 ? bytes : bytes.sublist(0, end));
}

/// Extracts the `path` record from PAX extended header [data]
/// (records of the form `"<length> <key>=<value>\n"`).
String? _paxPath(List<int> data) {
  String? path;
  var index = 0;
  while (index < data.length) {
    final space = data.indexOf(0x20, index);
    if (space < 0) {
      break;
    }
    final length = int.parse(ascii.decode(data.sublist(index, space)));
    final record = utf8.decode(data.sublist(space + 1, index + length - 1));
    final equals = record.indexOf('=');
    if (equals > 0 && record.substring(0, equals) == 'path') {
      path = record.substring(equals + 1);
    }
    index += length;
  }
  return path;
}

bool _sameBytes(List<int> a, List<int> b) {
  if (a.length != b.length) {
    return false;
  }
  for (var i = 0; i < a.length; i++) {
    if (a[i] != b[i]) {
      return false;
    }
  }
  return true;
}
